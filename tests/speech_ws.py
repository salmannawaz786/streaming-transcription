"""End-to-end test with real speech.

The tone-based smoke test proves audio reaches the decoder; it cannot check a
single word. This one streams a real utterance at real-time pace and checks
what actually comes back — which is the only way to see whether the live layer
is streaming word by word or arriving in lumps.

The fixture is generated by Windows TTS (see tests/make_fixture.ps1), so it is
reproducible and needs no committed audio.

    .venv/Scripts/python.exe -m tests.speech_ws
"""

from __future__ import annotations

import asyncio
import json
import sys
import time
import wave
from pathlib import Path

import websockets

URL = "ws://127.0.0.1:8100/ws"
FIXTURE = Path(__file__).resolve().parent / "fixtures" / "speech.wav"
CHUNK = 320  # 20ms at 16kHz

EXPECTED = "the quick brown fox jumps over the lazy dog"


def load() -> bytes:
    with wave.open(str(FIXTURE), "rb") as w:
        assert w.getframerate() == 16_000, f"fixture is {w.getframerate()}Hz, need 16k"
        assert w.getnchannels() == 1, "fixture must be mono"
        return w.readframes(w.getnframes())


async def main() -> int:
    pcm = load()
    duration = len(pcm) / 2 / 16_000
    print(f"streaming {duration:.1f}s of speech at real-time pace\n")

    partials: list[tuple[float, str]] = []
    finals: list[str] = []
    started = time.perf_counter()

    async with websockets.connect(URL, max_size=None) as ws:
        async def reader() -> None:
            async for raw in ws:
                msg = json.loads(raw)
                at = time.perf_counter() - started
                if msg["type"] == "partial":
                    partials.append((at, msg["text"]))
                    print(f"  {at:5.1f}s  partial [{msg.get('engine','whisper')}]  {msg['text']}")
                elif msg["type"] == "final":
                    finals.append(msg["text"])
                    print(f"  {at:5.1f}s  FINAL                  {msg['text']}")
                elif msg["type"] in ("speech_start", "speech_end"):
                    print(f"  {at:5.1f}s  {msg['type']} (stream t={msg['t']:.2f}s)")
                elif msg["type"] == "stats" and msg["kind"] == "final":
                    print(
                        f"  {at:5.1f}s  stats: audio={msg['audio_s']}s "
                        f"decode={msg['decode_ms']}ms queue={msg['queue_ms']}ms"
                    )

        task = asyncio.create_task(reader())
        # Pace against an absolute deadline, not a per-chunk sleep. Windows
        # timer granularity is ~15ms, so sleeping 20ms per 20ms chunk drifts
        # badly behind real time and inflates every latency reading.
        sent = 0
        step = CHUNK * 2 * 5  # 100ms per send, well clear of timer granularity
        for i in range(0, len(pcm), step):
            await ws.send(pcm[i:i + step])
            sent += len(pcm[i:i + step])
            target = started + (sent / 2 / 16_000)
            if (delay := target - time.perf_counter()) > 0:
                await asyncio.sleep(delay)
        # Let the tail decode land. Generous on purpose: a final on this box
        # can take several seconds, and a short wait here reads as "no final"
        # when the real answer is "not yet".
        await asyncio.sleep(15.0)
        task.cancel()

    print(f"\npartials: {len(partials)}   finals: {len(finals)}")

    failures = []
    if not finals:
        failures.append("no committed final")
    if not partials:
        failures.append("no partials — live layer produced nothing")
    else:
        # Word-by-word streaming shows many updates with a growing hypothesis.
        # Chunked Whisper partials show a handful. This is the number that
        # distinguishes the two, and the whole reason Vosk was added.
        print(f"partial updates per second of speech: {len(partials) / duration:.1f}")
        if len(partials) < duration:  # fewer than ~1/s is not "live"
            failures.append(
                f"only {len(partials)} partials over {duration:.1f}s — live text "
                "is arriving in lumps, not word by word"
            )

    joined = " ".join(finals).lower()
    hit = sum(1 for w in EXPECTED.split() if w in joined)
    print(f"expected words found in finals: {hit}/{len(EXPECTED.split())}")
    if hit < 6:
        failures.append(f"finals recognised only {hit}/9 expected words")

    # Word presence alone hides a clipped onset: "The quick brown fox" losing
    # its leading "The" still scores 9/9, because "the" recurs later in the
    # sentence. Check the opening explicitly.
    if finals and not finals[0].lower().lstrip().startswith("the quick"):
        failures.append(
            f"first final starts {finals[0][:24]!r} — leading word clipped"
        )

    for f in failures:
        print("FAIL:", f)
    print("\nOK" if not failures else "\nFAILED")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
