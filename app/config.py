"""Runtime profiles.

Device and model size are config, not code. The CPU-vs-GPU tradeoff table in
the README is generated by running the same service under different profiles.
"""

from __future__ import annotations

import os
from dataclasses import dataclass

SAMPLE_RATE = 16_000
FRAME_MS = 20
FRAME_SAMPLES = SAMPLE_RATE * FRAME_MS // 1000


@dataclass(frozen=True)
class Profile:
    name: str
    # Tiered decoding. Whisper pads every input to a 30s mel spectrogram, so
    # decode cost is dominated by fixed overhead rather than by clip length —
    # measured on an i7-7500U, 8x the audio (0.5s -> 4.0s) costs only 1.6x the
    # time. Shrinking windows therefore buys far less than it looks like it
    # should; model size and the NUMBER of decodes are what actually matter.
    #
    # So split the job. Partials are latency-critical but disposable: keep them
    # on the small model. Finals are accuracy-critical but NOT latency-critical
    # — they run after the speaker has stopped — so they can afford a bigger
    # model. Live text feels instant and the committed line reads correctly.
    fast_model: str      # partials
    accurate_model: str  # finals
    device: str
    compute_type: str
    # 0 means "as fast as the in-flight gate allows". The gate in Session is
    # what actually bounds partial work; this only throttles it further.
    partial_interval_s: float
    # Trailing audio kept as context when re-decoding, so words are not cut in
    # half at window boundaries.
    context_s: float
    # CTranslate2 defaults to 4 threads. On 2 physical cores that oversubscribes
    # and the threads fight; pinning to the physical count is measurably better.
    cpu_threads: int = 0  # 0 = let CTranslate2 decide (right for GPU)


PROFILES = {
    # i7-7500U, 2 physical / 4 logical cores. Measured (bench/threads.py,
    # 3s clip, int8, min-of-3 after warm-up):
    #
    #   tiny.en  beam=1   2 threads 2775ms | 4 threads 1781ms
    #   base.en  beam=1   2 threads 3483ms | 4 threads 3879ms
    #
    # 4 threads wins clearly for tiny.en and is repeatable. base.en flipped
    # between runs, so that one is noise on a thermally throttled laptop and no
    # winner is claimed. 4 is the default because of the tiny.en result.
    #
    # Default is tiny/tiny: base.en finals cost ~3.5-4s here, which buys
    # accuracy at a latency the demo cannot afford. Tiering is still the right
    # design — it just needs a machine that can pay for the accurate tier.
    "laptop": Profile(
        "laptop", "tiny.en", "tiny.en", "cpu", "int8",
        partial_interval_s=0.0, context_s=3.0, cpu_threads=4,
    ),
    # Accuracy over latency on the same hardware: better words, ~4s to commit.
    "laptop-tiered": Profile(
        "laptop-tiered", "tiny.en", "base.en", "cpu", "int8",
        partial_interval_s=0.0, context_s=3.0, cpu_threads=4,
    ),
    "cpu-server": Profile(
        "cpu-server", "base.en", "small.en", "cpu", "int8",
        partial_interval_s=0.0, context_s=5.0, cpu_threads=4,
    ),
    "gpu": Profile(
        "gpu", "small", "medium", "cuda", "float16",
        partial_interval_s=0.0, context_s=6.0,
    ),
}


def hotwords() -> str:
    """Domain vocabulary to bias decoding toward.

    Whisper will not invent a name it has no reason to expect. Feeding the
    proper nouns and jargon that actually occur is the cheapest accuracy win
    available for uncommon words.
    """
    default_words = "diarization, transcription, WebSocket, PyAnnote, Whisper, Vosk, CTranslate2"
    return os.getenv("SD_HOTWORDS", default_words).strip()


def active_profile() -> Profile:
    name = os.getenv("SD_PROFILE", "laptop")
    if name not in PROFILES:
        raise SystemExit(
            f"unknown SD_PROFILE {name!r}; choose from {', '.join(PROFILES)}"
        )
    return PROFILES[name]
